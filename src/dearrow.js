import { configRead, configAddChangeListener } from './config.js';
import { formatTitleInternal } from './vendor/dearrow/titleFormatter.js';
import { TitleFormatting, unicodeRegExpSupported } from './vendor/dearrow/shim.js';

/** Title formatting needs \p{...} regex support (Chrome 64+, webOS 5+). */
export const titleFormattingSupported = unicodeRegExpSupported;

/**
 * DeArrow - crowdsourced titles and thumbnails (https://dearrow.ajay.app).
 *
 * Branding is fetched per video, which JSON.parse cannot wait for, so this
 * works in two halves:
 *   1. applyDeArrow() runs inside adblock.js's JSON.parse hook and rewrites
 *      every tile whose branding is already resolved, so those render right
 *      the first time. Unknown videos are queued.
 *   2. When a lookup lands, sweepTiles() patches the tiles already on screen.
 *      Tiles are recreated as the user scrolls, so the sweep also reruns after
 *      every parse and key press.
 *
 * Selection and formatting follow the DeArrow extension: the top title or
 * thumbnail is used unless it is the original or voted below zero (locked
 * ones always win), and titles go through the extension's own formatter.
 */

const BRANDING_API = 'https://sponsor.ajay.app/api/branding';
const THUMBNAIL_API = 'https://dearrow-thumb.ajay.app/api/v1/getThumbnail';

const MAX_CONCURRENT = 4;
// ponytail: wipe-on-overflow, not LRU. A session rarely sees this many videos;
// each one costs at most a ~10 KB downscaled thumbnail plus its API response.
const CACHE_LIMIT = 1000;
// Tile thumbnails are drawn at this size. DeArrow serves full 1280x720 frames
// (16x the decoded memory of YouTube's 320x180 tile images), and with dozens
// of tiles that was enough to get the app killed for memory.
const THUMB_WIDTH = 320;
const THUMB_HEIGHT = 180;
const SWEEP_DELAY = 300;
// The thumbnail server renders a random frame when asked (generateNow) but
// answers 204 until it is done, which takes well over 5s. Look again later.
const RANDOM_FRAME_RETRIES_MS = [10000, 30000];
const SCAN_MAX_NODES = 20000;
const SCAN_MAX_DEPTH = 24;

const VIDEO_ID_RE = /(?:\/vi(?:_webp)?\/|[?&#]videoID=)([\w-]{11})/;

// YouTube's own frames from the start / middle / end of every video.
const AUTOGENERATED_FRAMES = { start: 'hq1', middle: 'hq2', end: 'hq3' };
// A transparent pixel. The fragment keeps the video id readable from the
// tile's background, which is how sweepTiles() finds the tile again.
const BLANK_THUMB = 'data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7#videoID=';

const FORMATTING = {
  disable: TitleFormatting.Disable,
  title_case: TitleFormatting.TitleCase,
  sentence_case: TitleFormatting.SentenceCase,
  lower_case: TitleFormatting.LowerCase,
  first_letter_uppercase: TitleFormatting.FirstLetterUppercase,
  capitalize_words: TitleFormatting.CapitalizeWords
};

export const DEARROW_CONFIG_KEYS = [
  'enableDeArrow',
  'dearrowReplaceTitles',
  'dearrowUseCrowdsourcedTitles',
  'dearrowTitleFormatting',
  'dearrowFormatOriginalTitles',
  'dearrowFormatCustomTitles',
  'dearrowCleanEmojis',
  'dearrowReplaceThumbnails',
  'dearrowThumbnailFallback',
  'dearrowAutogeneratedFrame'
];

/**
 * videoId -> {
 *   original, originalThumb, duration  - what YouTube sent, for formatting,
 *                                        random frames and restoring
 *   raw                                - branding API response
 *   title, thumb                       - what to show; null = the original
 * }
 */
const videos = new Map();
const queue = [];
let active = 0;
let sweepTimer = null;
// Bumped on every settings change so a slow lookup can't write stale output.
let generation = 0;

function isEnabled() {
  return !!configRead('enableDeArrow');
}

function isTrusted(entry) {
  return entry && !entry.original && (entry.locked || entry.votes >= 0);
}

function thumbnailUrl(videoId, time) {
  return `${THUMBNAIL_API}?videoID=${videoId}&time=${time}`;
}

// "1:02:03" -> 3723
function parseDuration(text) {
  if (!text || !/^\d+(?::\d+)+$/.test(text)) return null;
  return text.split(':').reduce((total, part) => total * 60 + +part, 0);
}

/** source URL -> small object/data URL, and small URL -> videoId. */
const smallThumbs = new Map();
const thumbOwners = new Map();
// source URL -> in-flight load, so a settings change mid-download can't
// create a second blob for the same image (only one would ever be revoked).
const loadingThumbs = new Map();

/**
 * Download a thumbnail and hand back a 320x180 copy, cropped to 16:9 (which
 * also trims the letterbox off YouTube's 4:3 hq1-hq3 frames). Resolves null
 * when the image doesn't load - the thumbnail server answers 204 for frames
 * it hasn't rendered, which would otherwise leave the tile blank.
 */
function loadThumb(url, videoId) {
  const cached = smallThumbs.get(url);
  if (cached) return Promise.resolve(cached);
  let loading = loadingThumbs.get(url);
  if (!loading) {
    loading = downscaleThumb(url, videoId);
    loadingThumbs.set(url, loading);
    loading.then(() => loadingThumbs.delete(url));
  }
  return loading;
}

function downscaleThumb(url, videoId) {
  return new Promise((done) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onerror = () => done(null);
    img.onload = () => {
      const w = img.naturalWidth;
      const h = img.naturalHeight;
      if (!w || !h) return done(null);
      const finish = (small) => {
        if (small) {
          smallThumbs.set(url, small);
          thumbOwners.set(small, videoId);
        }
        done(small);
      };
      try {
        const canvas = document.createElement('canvas');
        canvas.width = THUMB_WIDTH;
        canvas.height = THUMB_HEIGHT;
        const cropW = Math.min(w, h * 16 / 9);
        const cropH = cropW * 9 / 16;
        canvas.getContext('2d').drawImage(img, (w - cropW) / 2, (h - cropH) / 2, cropW, cropH,
          0, 0, THUMB_WIDTH, THUMB_HEIGHT);
        // toBlob is Chrome 50+; webOS 3/4 get a data URL instead.
        if (canvas.toBlob) {
          canvas.toBlob((blob) => finish(blob ? URL.createObjectURL(blob) : null), 'image/jpeg', 0.85);
        } else {
          // Tag it: two videos with identical frames would share a data URL.
          finish(canvas.toDataURL('image/jpeg', 0.85) + '#videoID=' + videoId);
        }
      } catch {
        // Tainted canvas or out of memory: keep YouTube's thumbnail.
        finish(null);
      }
    };
    img.src = url;
  });
}

function forgetThumbs() {
  smallThumbs.forEach((small) => {
    if (small.indexOf('blob:') === 0) URL.revokeObjectURL(small);
  });
  smallThumbs.clear();
  thumbOwners.clear();
}

function formatTitle(title, isCustom) {
  const supported = titleFormattingSupported;
  const formatting = supported ? FORMATTING[configRead('dearrowTitleFormatting')] : undefined;
  return formatTitleInternal(
    title,
    isCustom,
    formatting ?? TitleFormatting.Disable,
    supported && !!configRead('dearrowCleanEmojis'),
    !!configRead('dearrowFormatCustomTitles'),
    !!configRead('dearrowFormatOriginalTitles')
  );
}

async function resolveTitle(video) {
  if (!configRead('dearrowReplaceTitles')) return null;

  const custom = configRead('dearrowUseCrowdsourcedTitles') && video.raw?.titles?.[0];
  if (isTrusted(custom)) return formatTitle(custom.title, true);

  if (!video.original) return null;
  const formatted = await formatTitle(video.original, false);
  return formatted !== video.original ? formatted : null;
}

// The server's random position (sent even for videos it has never seen), so
// the frame matches the one other DeArrow users already had rendered. No
// response (offline) means no random frame: the auto-generated one stays.
function randomFrameTime(video) {
  const duration = video.raw?.videoDuration || video.duration;
  const randomTime = video.raw?.randomTime;
  return duration && randomTime != null ? randomTime * duration : null;
}

/**
 * Resolve the thumbnail, calling show() with each improvement: a random
 * frame can take the thumbnail server tens of seconds to render, so the
 * auto-generated frame stands in until it does - as in the extension.
 */
async function resolveThumb(videoId, video, gen, show) {
  if (!configRead('dearrowReplaceThumbnails')) return show(null);

  const custom = video.raw?.thumbnails?.[0];
  if (isTrusted(custom) && custom.timestamp != null) {
    return show(await loadThumb(thumbnailUrl(videoId, custom.timestamp), videoId));
  }
  if (custom?.original && (custom.locked || custom.votes >= 0)) return show(null);

  const fallback = configRead('dearrowThumbnailFallback');
  if (fallback === 'original') return show(null);
  if (fallback === 'blank') return show(BLANK_THUMB + videoId);

  const frame = AUTOGENERATED_FRAMES[configRead('dearrowAutogeneratedFrame')] || 'hq1';
  const autogenerated = `https://i.ytimg.com/vi/${videoId}/${frame}.jpg`;
  const time = fallback === 'random' ? randomFrameTime(video) : null;
  if (time === null) return show(await loadThumb(autogenerated, videoId));

  const url = thumbnailUrl(videoId, time);
  const ready = await loadThumb(url + '&generateNow=true', videoId);
  if (ready) return show(ready);
  show(await loadThumb(autogenerated, videoId));
  // Not awaited: the lookup worker moves on to the next video meanwhile.
  const retry = (delays) => {
    if (!delays.length) return;
    setTimeout(async () => {
      if (gen !== generation) return;
      const small = await loadThumb(url, videoId);
      if (small) show(small);
      else retry(delays.slice(1));
    }, delays[0]);
  };
  retry(RANDOM_FRAME_RETRIES_MS);
}

async function resolve(videoId, video) {
  if (!isEnabled()) return;
  const gen = generation;
  const title = await resolveTitle(video);
  if (gen !== generation) return;
  video.title = title;
  video.resolved = true;
  scheduleSweep();

  await resolveThumb(videoId, video, gen, (thumb) => {
    if (gen !== generation) return;
    const changed = video.thumb !== thumb;
    video.thumb = thumb;
    if (changed) scheduleSweep();
  });
}

async function lookup(videoId) {
  const video = videos.get(videoId);
  if (!video) return;
  if (video.fetched) return resolve(videoId, video);
  try {
    const res = await fetch(`${BRANDING_API}?videoID=${videoId}`);
    // 404 just means "no submissions" and still carries randomTime and the
    // exact videoDuration, which random frames need to hit the shared cache.
    if (res.ok || res.status === 404) video.raw = await res.json();
  } catch {
    // Offline or blocked - formatting the original title can still apply.
  }
  video.fetched = true;
  await resolve(videoId, video);
}

function pump() {
  while (active < MAX_CONCURRENT && queue.length && isEnabled()) {
    const videoId = queue.shift();
    active++;
    const next = () => {
      active--;
      pump();
    };
    lookup(videoId).then(next, next);
  }
}

// YouTube keeps parsed responses and re-renders cached pages from them, so
// what applyToTile writes must be undone too, not just the live tiles.
// ponytail: last few patches per video only; older cached pages may keep a
// DeArrow title until YouTube refetches them.
const PATCHES_PER_VIDEO = 8;

function applyToTile(tile, video) {
  const title = video.title && tile.metadata?.tileMetadataRenderer?.title;
  const thumbnail = video.thumb && tile.header?.tileHeaderRenderer?.thumbnail;
  if (!title && !thumbnail) return;
  // Only the two small objects are kept, not the tile or the response.
  const patch = { title: null, simpleText: undefined, runs: undefined, thumbnail: null, thumbnails: null };
  if (title) {
    video.shownTitle = video.title;
    patch.title = title;
    patch.simpleText = title.simpleText;
    patch.runs = title.runs;
    title.simpleText = video.title;
    delete title.runs;
  }
  if (thumbnail) {
    video.shownThumb = video.thumb;
    patch.thumbnail = thumbnail;
    patch.thumbnails = thumbnail.thumbnails;
    thumbnail.thumbnails = [{ url: video.thumb, width: 1280, height: 720 }];
  }
  if (!video.patches) video.patches = [];
  if (video.patches.push(patch) > PATCHES_PER_VIDEO) video.patches.shift();
}

/** Put YouTube's own titles and thumbnails back into the stored responses. */
function unpatchResponses() {
  videos.forEach((video) => {
    if (!video.patches) return;
    video.patches.forEach((patch) => {
      if (patch.title) {
        if (patch.simpleText === undefined) delete patch.title.simpleText;
        else patch.title.simpleText = patch.simpleText;
        if (patch.runs) patch.title.runs = patch.runs;
      }
      if (patch.thumbnail) patch.thumbnail.thumbnails = patch.thumbnails;
    });
    video.patches = null;
  });
}

function readTile(tile) {
  const title = tile.metadata?.tileMetadataRenderer?.title;
  const header = tile.header?.tileHeaderRenderer;
  let duration = null;
  const overlays = header?.thumbnailOverlays;
  if (Array.isArray(overlays)) {
    for (let i = 0; i < overlays.length && duration === null; i++) {
      duration = parseDuration(overlays[i]?.thumbnailOverlayTimeStatusRenderer?.text?.simpleText);
    }
  }
  return {
    original: title?.simpleText ?? (title?.runs ? title.runs.map((r) => r.text).join('') : null),
    originalThumb: header?.thumbnail?.thumbnails?.[0]?.url ?? null,
    duration
  };
}

function setText(el, text) {
  // Edit the existing text node rather than replacing it: the renderer keeps
  // a handle on that node and reuses the tile for other videos.
  const first = el.firstChild;
  if (first && first.nodeType === 3 && !first.nextSibling) first.nodeValue = text;
  else el.textContent = text;
}

/**
 * Bring rendered tiles in line with `videos`. With `restoreAll`, put back
 * every original we replaced (DeArrow switched off).
 */
function sweepTiles(restoreAll) {
  // A pending sweep would re-apply what restoreAll just put back.
  clearTimeout(sweepTimer);
  sweepTimer = null;
  if (videos.size === 0) return;

  const tiles = document.querySelectorAll('ytlr-tile-renderer');
  for (let i = 0; i < tiles.length; i++) {
    const thumbEl = tiles[i].querySelector('ytlr-thumbnail-details');
    const background = thumbEl?.style.backgroundImage;
    const shownUrl = background && /url\("?([^")]+)"?\)/.exec(background);
    const owner = shownUrl && thumbOwners.get(shownUrl[1]);
    const match = !owner && background && VIDEO_ID_RE.exec(background);
    const video = videos.get(owner || (match && match[1]));
    if (!video) continue;

    const wantThumb = restoreAll ? null : video.thumb;
    if (wantThumb) {
      // Must be the top layer, not just present: Max Thumbnail Quality can
      // stack an upgraded original on top of whatever the tile shows.
      const at = background.indexOf(wantThumb);
      if (at === -1 || at > 5) thumbEl.style.backgroundImage = `url("${wantThumb}")`;
      video.shownThumb = wantThumb;
    } else if (video.shownThumb && video.originalThumb && background.indexOf(video.shownThumb) !== -1) {
      // Only undo an image we set ourselves.
      thumbEl.style.backgroundImage = `url("${video.originalThumb}")`;
    }

    const titleEl = tiles[i].querySelector('ytlr-tile-metadata-renderer yt-formatted-string');
    if (!titleEl) continue;
    const wantTitle = restoreAll ? null : video.title;
    if (wantTitle) {
      if (titleEl.textContent !== wantTitle) setText(titleEl, wantTitle);
      video.shownTitle = wantTitle;
    } else if (video.shownTitle && video.original && titleEl.textContent === video.shownTitle) {
      // Only undo text we wrote ourselves; anything else is YouTube's.
      setText(titleEl, video.original);
    }
  }
}

function scheduleSweep() {
  if (!sweepTimer && isEnabled()) sweepTimer = setTimeout(() => sweepTiles(false), SWEEP_DELAY);
}

function wipeCache() {
  // Put originals back while we still know them; the blobs go next.
  sweepTiles(true);
  unpatchResponses();
  generation++;
  videos.clear();
  queue.length = 0;
  forgetThumbs();
}

/** Called from adblock.js's JSON.parse hook with every InnerTube response. */
export function applyDeArrow(data) {
  if (!data || typeof data !== 'object') return;
  // Before patching anything: a wipe mid-response would revoke blobs this
  // same response was just given.
  if (videos.size >= CACHE_LIMIT || smallThumbs.size >= CACHE_LIMIT) wipeCache();

  // Breadth-first so videos are queued in response order, i.e. screen order.
  const nodes = [data, 0];
  let index = 0;
  while (index < nodes.length && index < SCAN_MAX_NODES * 2) {
    const node = nodes[index++];
    const depth = nodes[index++];
    if (depth > SCAN_MAX_DEPTH) continue;

    const tile = node.tileRenderer;
    if (tile && tile.contentType === 'TILE_CONTENT_TYPE_VIDEO' && tile.contentId) {
      const videoId = tile.contentId;
      const video = videos.get(videoId);
      if (video?.resolved) applyToTile(tile, video);
      else if (!video) {
        const info = readTile(tile);
        videos.set(videoId, {
          original: info.original,
          originalThumb: info.originalThumb,
          duration: info.duration,
          raw: null,
          title: null,
          thumb: null,
          resolved: false
        });
        queue.push(videoId);
      }
      continue;
    }

    for (const key in node) {
      const value = node[key];
      if (value && typeof value === 'object') nodes.push(value, depth + 1);
    }
  }

  pump();
  scheduleSweep();
}

function onSettingsChange() {
  generation++;
  // Stored responses get re-patched with the new output as they are parsed.
  unpatchResponses();
  if (!isEnabled()) {
    sweepTiles(true);
    return;
  }
  // Re-resolve everything through the queue (stored API responses are
  // reused), newest first since those are the ones likely on screen.
  queue.length = 0;
  videos.forEach((video, videoId) => {
    queue.push(videoId);
  });
  queue.reverse();
  pump();
}

DEARROW_CONFIG_KEYS.forEach((key) => {
  configAddChangeListener(key, onSettingsChange);
});

// Navigation is what makes the app recreate tiles, so a key press is the
// cheapest signal that freshly built tiles may need patching again.
document.addEventListener('keydown', () => {
  if (videos.size) scheduleSweep();
}, true);
