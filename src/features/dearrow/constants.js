// DeArrow's servers, limits and timings (features/dearrow).

// Branding (titles, thumbnails, the random frame time) per video, as the
// extension asks for it for tiles; the thumbnail server renders frames.
export const BRANDING_API = 'https://sponsor.ajay.app/api/branding';
export const THUMBNAIL_API = 'https://dearrow-thumb.ajay.app/api/v1/getThumbnail';
// A branding answer that takes longer is dropped (the original stays).
export const FETCH_TIMEOUT_MS = 8000;
// Branding lookups at a time; the rest wait in the queue, in screen order.
export const MAX_CONCURRENT = 4;

// Videos (and thumbnail copies) remembered before everything is dropped and
// the originals are put back: a session rarely sees this many.
export const CACHE_LIMIT = 1000;
// How wide DeArrow's copies of thumbnails are drawn (16:9, never wider than the
// source), following Max Thumbnail Quality so they match the tiles around
// them: hqdefault's 480 while it is off, sddefault's 640 in Smooth (SD),
// maxresdefault's 1280 in Original and Fast, which both reach it.
export const COPY_WIDTHS = { off: 480, sd: 640, safe: 1280, eager: 1280 };
// Where canvas has no toBlob (webOS 3 and 4) the copies are data URLs,
// strings in the page's own memory: kept at hqdefault's size there.
export const DATA_URL_WIDTH = 480;
// How much the kept copies may weigh before everything starts over: JPEG
// blobs (a 1280x720 frame is 100 to 200 KB), or data URL text on webOS 3 and
// 4 (about 40 KB at 480 wide).
export const BLOB_BUDGET = 48 * 1024 * 1024;
export const DATA_URL_BUDGET = 4 * 1024 * 1024;

// How long after a change the rendered tiles are brought in line, so a burst
// of answers is one pass over the page.
export const SWEEP_DELAY = 300;
// The thumbnail server answers 204 until it has rendered a random frame, which
// takes well over 5 s: the frame is asked for again after these delays.
export const RANDOM_FRAME_RETRIES_MS = [10000, 30000];
// The tiles of stored responses remembered per video (tiles.js): the last
// ones; an older cached page may keep a DeArrow title until YouTube asks again.
export const TILES_PER_VIDEO = 8;
// The label of the DeArrow badge in a tile's metadata line: the sweep finds it
// by this text and draws the logo over it. A fisheye, so even undrawn it
// looks like the logo.
export const BADGE_MARK = '\u25C9';

// The bounded walk over a response that finds its video tiles.
export const SCAN_MAX_NODES = 20000;
export const SCAN_MAX_DEPTH = 24;

// YouTube's own frames from the start, middle and end of every video, by the
// Without a crowdsourced thumbnail value that picks each.
export const AUTOGENERATED_FRAMES = { start: 'hq1', middle: 'hq2', end: 'hq3' };
// A transparent pixel for the Blank fallback. The fragment carries the video
// id, which is how the sweep finds the tile again (VIDEO_ID_RE).
export const BLANK_THUMB =
  'data:image/gif;base64,R0lGODlhAQABAIAAAAAAAP///yH5BAEAAAAALAAAAAABAAEAAAIBRAA7#videoID=';
// The video id in a thumbnail URL: YouTube's /vi/ and /vi_webp/ paths, or the
// videoID parameter or fragment of DeArrow's own.
export const VIDEO_ID_RE = /(?:\/vi(?:_webp)?\/|[?&#]videoID=)([\w-]{11})/;

// Every setting the feature reads: a change of any re-resolves what is shown.
export const DEARROW_CONFIG_KEYS = [
  'enableDeArrow',
  'dearrowCrowdTitles',
  'dearrowTitleFormatting',
  'dearrowCleanEmojis',
  'dearrowCrowdThumbnails',
  'dearrowThumbnailFallback',
  'dearrowShowBadge',
  // The copies' size follows Max Thumbnail Quality.
  'upgradeThumbnails',
  'thumbnailQualityMode'
];
